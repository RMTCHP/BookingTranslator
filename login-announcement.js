function showLoginAnnouncement() {
  let language = "th";
  const bindLanguageButtons = () => {
    document.querySelectorAll("[data-announcement-language]").forEach((button) => {
      button.addEventListener("click", () => {
        language = button.dataset.announcementLanguage;
        render();
      });
    });
  };
  const render = () => {
    const notice = LOGIN_ANNOUNCEMENT[language];
    Swal.update({
      title: notice.title,
      html: `
        <style>
          .announcement-language-switcher { display:flex; gap:5px; justify-content:flex-end; margin:-2px 0 8px; }
          .announcement-language-switcher button { width:44px; height:32px; display:inline-flex; align-items:center; justify-content:center; border:1px solid #c7d9ef; border-radius:8px; background:#f4f8fe; padding:4px; cursor:pointer; }
          .announcement-language-switcher button.active { background:#1e528f; border-color:#1e528f; color:#fff; box-shadow:0 4px 10px rgba(30,82,143,.22); }
          .announcement-language-switcher button svg { width:25px; height:17px; display:block; border-radius:2px; box-shadow:0 1px 2px rgba(13,42,76,.18); }
          .announcement-content { max-height:56vh; overflow-y:auto; padding:0 9px 4px; text-align:left; font-size:14px; line-height:1.55; }
          .announcement-content h3 { margin:0 0 6px; color:#173d70; font-size:17px; }
          .announcement-content p { margin:8px 0; }
          .announcement-content ol { margin:8px 0; padding-left:22px; }
          .announcement-content li { margin:6px 0; }
          .announcement-subtitle { margin-top:0 !important; color:#52759d; font-weight:700; }
          .announcement-note { border-top:1px solid #d8e4f2; padding-top:8px; color:#274e78; }
          .announcement-signoff { margin:12px 0 2px !important; color:#173d70; }
        </style>
        <div class="announcement-language-switcher">
          ${Object.entries(LOGIN_ANNOUNCEMENT).map(([key, item]) => `<button type="button" data-announcement-language="${key}" class="${key === language ? "active" : ""}" aria-label="${item.language}" title="${item.language}">${item.flag}</button>`).join("")}
        </div>
        <div class="announcement-content">${notice.content}</div>`,
    });
    requestAnimationFrame(bindLanguageButtons);
  };

  Swal.fire({
    icon: "info",
    title: "",
    html: "",
    showConfirmButton: false,
    showCloseButton: true,
    allowOutsideClick: true,
    customClass: {
      popup: "swal-login-announcement-popup",
      title: "swal-login-announcement-title",
      htmlContainer: "swal-login-announcement-html"
    },
    didOpen: render
  });
}
